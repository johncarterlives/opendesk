const ownDomainPass = "Authentication-Results: mx.in.test; spf=pass smtp.mailfrom=acme.test; dkim=pass header.d=acme.test; dmarc=pass header.from=acme.test\r\n"

// shopMail is mail the workspace sent someone, with the mailbox copied.
func shopMail(from, to, cc, extra string) (raw, msgID string) {
	msgID = "order-" + crypto.RandomString(10) + "@shop.acme.test"
	raw = "From: Acme Shop <" + from + ">\r\nTo: " + to + "\r\n"
	if cc != "" {
		raw += "Cc: " + cc + "\r\n"
	}
	raw += "Subject: Your order\r\nMessage-ID: <" + msgID + ">\r\n" + extra + "\r\nThanks for your order\r\n"
	return raw, msgID
}

func answer(from, to, inReplyTo string) string {
	return "From: " + from + "\r\nTo: " + to + "\r\nSubject: Re: Your order\r\nMessage-ID: <a" + crypto.RandomString(10) + "@customer.test>\r\n" +
		"In-Reply-To: <" + inReplyTo + ">\r\nReferences: <" + inReplyTo + ">\r\n\r\nWhere is my parcel?\r\n"
}

func (w *world) contactEmail(t domain.Ticket) string {
	w.t.Helper()
	if t.Contact == nil || t.Contact.Email == nil {
		w.t.Fatalf("ticket %d has no contact email", t.Number)
	}
	return *t.Contact.Email
}

// replyTo is where an email to the ticket's customer goes.
func (w *world) replyTo(t domain.Ticket) []string {
	w.t.Helper()
	c := w.contactEmail(t)
	to, err := domain.ReplyRecipients(w.ctx, w.d.DB.Pool, w.wid, t.ID, &c, []string{c})
	if err != nil {
		w.t.Fatal(err)
	}
	return to
}

// sentTo sends an agent reply on the ticket and returns the To it went to.
func (w *world) sentTo(ticketID uuid.UUID) string {
	w.t.Helper()
	var sent [][]byte
	prev := w.s.rawSend
	w.s.rawSend = func(_ context.Context, _ string, _ []string, raw []byte) error { sent = append(sent, raw); return nil }
	defer func() { w.s.rawSend = prev }()
	if err := w.s.sendMessage(w.ctx, w.wid, w.agentReply(ticketID, "On its way", ""), false); err != nil {
		w.t.Fatal(err)
	}
	env, err := enmime.ReadEnvelope(bytes.NewReader(sent[0]))
	if err != nil {
		w.t.Fatal(err)
	}
	return env.GetHeader("To")
}

func TestWorkspaceMailIsAboutItsCustomer(t *testing.T) {
	w := newWorld(t)
	m := w.mailbox(InboundForwarding, OutboundSystem, func(m *mailboxRow, _ *credentials) {
		m.Aliases = []string{"sales@acme.test"}
		m.AutoReplyEnabled, m.AutoReplyHTML = true, "<p>Got it</p>"
	})
	buyer := customer()

	// The shop's order confirmation from an alias to the buyer, copied to the mailbox: the
	// buyer is the customer, and the message stays the shop's.
	raw, orderID := shopMail("sales@acme.test", "Bea Buyer <"+buyer+">", m.Email, "Reply-To: orders@acme.test\r\n")
	id := w.receive(m, raw)
	if st, reason := w.inbound(id); st != "processed" {
		t.Fatalf("order confirmation: %s %s", st, reason)
	}
	msg := w.messageFor(id)
	tk := w.ticket(msg.TicketID)
	if got := w.contactEmail(tk); got != buyer || tk.Contact.Name != "Bea Buyer" {
		t.Fatalf("contact %s %q, want the buyer", got, tk.Contact.Name)
	}
	var author string
	if err := w.d.DB.Pool.QueryRow(w.ctx, `SELECT c.email FROM messages ms JOIN contacts c ON c.id = ms.author_contact_id WHERE ms.id = $1`, msg.ID).Scan(&author); err != nil {
		t.Fatal(err)
	}
	if msg.FromEmail != "sales@acme.test" || author != "sales@acme.test" || msg.Direction != "inbound" {
		t.Fatalf("message from %s author %s %s", msg.FromEmail, author, msg.Direction)
	}
	// The shop's Reply-To is not the customer's: replies go to the buyer.
	if to := w.replyTo(tk); len(to) != 1 || to[0] != buyer {
		t.Fatalf("reply recipients %v", to)
	}
	if to := w.sentTo(tk.ID); !strings.Contains(to, buyer) {
		t.Fatalf("agent reply To %q", to)
	}
	// Still the workspace's own mail: no auto-reply.
	if n := w.jobCount("email.send_ticket_email", "", ""); n != 0 {
		t.Fatalf("auto-reply to workspace mail: %d", n)
	}
	// Surveys and other ticket emails go to the buyer too.
	if _, err := w.d.Jobs.Insert(w.ctx, jobs.SendTicketEmailArgs{WorkspaceID: w.wid, TicketID: tk.ID, Subject: "How did we do?",
		HTML: "<p>Rate us</p>", AutoGenerated: true}, nil); err != nil {
		t.Fatal(err)
	}
	if sent := w.sendQueued(t); len(sent) != 1 || !strings.Contains(sent[0].GetHeader("To"), buyer) {
		t.Fatalf("ticket email %v", sent)
	}

	// The buyer answers: the reply joins the ticket, which stays theirs.
	id = w.receive(m, answer(buyer, "sales@acme.test", orderID))
	if got := w.messageFor(id).TicketID; got != tk.ID {
		t.Fatalf("answer opened ticket %v", got)
	}
	if got := w.contactEmail(w.ticket(tk.ID)); got != buyer {
		t.Fatalf("contact after answer %s", got)
	}
	// The shop's next mail in the conversation threads in too, and is not a customer reply.
	next, _ := shopMail("sales@acme.test", buyer, m.Email, "In-Reply-To: <"+orderID+">\r\nReferences: <"+orderID+">\r\n")
	before := w.jobCount(jobs.TicketTriggerArgs{}.Kind(), "trigger", jobs.TriggerCustomerReplied)
	id = w.receive(m, next)
	if got := w.messageFor(id).TicketID; got != tk.ID {
		t.Fatalf("shipping notice opened ticket %v", got)
	}
	if n := w.jobCount(jobs.TicketTriggerArgs{}.Kind(), "trigger", jobs.TriggerCustomerReplied); n != before {
		t.Fatalf("customer_replied for the shop's own mail: %d -> %d", before, n)
	}

	// Mail from the workspace with no outside recipient keeps its sender as the customer.
	id = w.receive(m, rawMail("Acme <sales@acme.test>", m.Email, "Stock report", "Cc: "+w.forwardAddr(m, "")+"\r\n"))
	if got := w.contactEmail(w.ticket(w.messageFor(id).TicketID)); got != "sales@acme.test" {
		t.Fatalf("contact of internal mail %s", got)
	}
	// Cc counts when To names only workspace addresses.
	other := customer()
	raw, _ = shopMail(m.Email, "sales@acme.test", other, "")
	id = w.receive(m, raw)
	if got := w.contactEmail(w.ticket(w.messageFor(id).TicketID)); got != other {
		t.Fatalf("contact from Cc %s, want %s", got, other)
	}
}

func TestOwnDomainCopyIsAboutItsCustomer(t *testing.T) {
	w := newWorld(t)
	m := w.mailbox(InboundForwarding, OutboundSystem, func(m *mailboxRow, _ *credentials) {
		m.AutoReplyEnabled, m.AutoReplyHTML = true, "<p>Got it</p>"
	})
	contactOf := func(raw string) string {
		t.Helper()
		id := w.receive(m, raw)
		if st, reason := w.inbound(id); st != "processed" {
			t.Fatalf("%s %s", st, reason)
		}
		return w.contactEmail(w.ticket(w.messageFor(id).TicketID))
	}

	// An authenticated copy of the organisation's mail to someone outside it, from an
	// address that is not a mailbox: the recipient is the customer, and nothing answers it.
	buyer := customer()
	raw, _ := shopMail("shop@acme.test", buyer, "", ownDomainPass)
	if got := contactOf(raw); got != buyer {
		t.Fatalf("authenticated copy: contact %s", got)
	}
	if n := w.jobCount("email.send_ticket_email", "", ""); n != 0 {
		t.Fatalf("auto-reply to the organisation's own mail: %d", n)
	}
	for name, raw := range map[string]string{
		// Not proven to be the organisation's.
		"unauthenticated": func() string { r, _ := shopMail("shop@acme.test", customer(), "", ""); return r }(),
		// Written to the help desk, about someone it copies.
		"to the mailbox": func() string { r, _ := shopMail("shop@acme.test", m.Email, customer(), ownDomainPass); return r }(),
		// Written to a colleague.
		"inside the organisation": func() string { r, _ := shopMail("shop@acme.test", "ops@acme.test", "", ownDomainPass); return r }(),
	} {
		if got := contactOf(raw); got != "shop@acme.test" {
			t.Errorf("%s: contact %s, want the sender", name, got)
		}
	}
}

func TestOutsideAnswerTakesOverWorkspaceContact(t *testing.T) {
	w := newWorld(t)
	m := w.mailbox(InboundForwarding, OutboundSystem, func(m *mailboxRow, _ *credentials) {
		m.Aliases = []string{"sales@acme.test"}
	})
	buyer := customer()
	raw, orderID := shopMail("sales@acme.test", buyer, m.Email, "")
	tk := w.ticket(w.messageFor(w.receive(m, raw)).TicketID)
	// A ticket from before workspace mail named its customer: the contact is the alias.
	var alias uuid.UUID
	if err := w.d.DB.Pool.QueryRow(w.ctx, `SELECT author_contact_id FROM messages WHERE ticket_id = $1`, tk.ID).Scan(&alias); err != nil {
		t.Fatal(err)
	}
	mustExec(t, w.d, `UPDATE tickets SET contact_id = $2 WHERE id = $1`, tk.ID, alias)

	// Someone the conversation never addressed answers: they join it, and it stays as it is.
	w.receive(m, answer(customer(), "sales@acme.test", orderID))
	if got := w.contactEmail(w.ticket(tk.ID)); got != "sales@acme.test" {
		t.Fatalf("contact after a newcomer %s", got)
	}

	// The buyer the shop wrote to answers: they are the customer, and replies go to them.
	friend := customer()
	w.receive(m, answer("Bea Buyer <"+buyer+">", "sales@acme.test, "+friend, orderID))
	tk = w.ticket(tk.ID)
	if got := w.contactEmail(tk); got != buyer {
		t.Fatalf("contact after the buyer answered %s", got)
	}
	var data map[string]any
	if err := w.d.DB.Pool.QueryRow(w.ctx, `SELECT data FROM activities WHERE ticket_id = $1 AND type = 'contact_changed'`, tk.ID).Scan(&data); err != nil {
		t.Fatalf("contact_changed activity: %v", err)
	}
	if data["reason"] != "customer_answered" || data["to"].(map[string]any)["id"] != tk.Contact.ID.String() {
		t.Fatalf("activity %v", data)
	}
	if to := w.replyTo(tk); len(to) != 1 || to[0] != buyer {
		t.Fatalf("reply recipients %v", to)
	}
	if to := w.sentTo(tk.ID); !strings.Contains(to, buyer) {
		t.Fatalf("agent reply To %q", to)
	}
	// A customer who is not a workspace address is never replaced, even by someone they wrote to.
	w.receive(m, answer(friend, buyer, orderID))
	if got := w.contactEmail(w.ticket(tk.ID)); got != buyer {
		t.Fatalf("contact moved off the customer: %s", got)
	}
	if n := w.count(`SELECT count(*) FROM activities WHERE ticket_id = $1 AND type = 'contact_changed'`, tk.ID); n != 1 {
		t.Fatalf("contact changes %d", n)
	}

	// The shop's own next mail on such a ticket moves it to the customer it is written to.
	raw, orderID = shopMail("sales@acme.test", buyer, m.Email, "")
	old := w.ticket(w.messageFor(w.receive(m, raw)).TicketID)
	mustExec(t, w.d, `UPDATE tickets SET contact_id = $2 WHERE id = $1`, old.ID, alias)
	next, _ := shopMail("sales@acme.test", buyer, m.Email, "In-Reply-To: <"+orderID+">\r\n")
	if got := w.messageFor(w.receive(m, next)).TicketID; got != old.ID {
		t.Fatalf("shop mail opened ticket %v", got)
	}
	if got := w.contactEmail(w.ticket(old.ID)); got != buyer {
		t.Fatalf("contact after the shop's mail %s", got)
	}
}
